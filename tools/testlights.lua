-- ---------------------------------------------------------------------------
-- testlights.lua - ORO's lights-and-shadows test rig
--
-- An AUTOMATIC sequence of thirteen cases that exercises the patched client's
-- local-light work: spot shadow maps (one per light or per cluster, up to six),
-- the sticky selection when there are more lights than maps, the wide stadium
-- flood, point-light shadows (aimed map or five-face cube), spots ranking before
-- points, the sixteen-light budget, the day/night split, and the crowded pad's
-- capped floods. Every case says on
-- screen what it shows, what to expect, which Launchpad row it needs and what
-- the ORO lcl dbg log line should read. A full pass is about six and a half
-- minutes, so anyone can record it and send the video.
--
-- HOW TO RUN: the "Lights and shadows" scenario
-- (Scenarios\ORO\5 Night and lights) carries the line
--     Script testlights
-- in its environment block, so Orbiter runs this file as the scenario loads
-- (the LuaInline module must be ticked in the Launchpad's Modules tab). The
-- scenario holds ONE landed DeltaGlider (GL-01) on the flat ground at KSC, at
-- night; everything else (lamp posts, extra vessels) is spawned by this script
-- relative to the DG and deleted at the end. It can also be started from the Lua
-- console at any such scenario with run('testlights').
--
-- NOTE: THE RIG IS POSITION- AND HEADING-AGNOSTIC BY CONSTRUCTION, so moving the DG
-- needs no edit here: the reference lng/lat/heading are read from the vessel at
-- load (dgLng/dgLat/hdg0 below), every placement is given in VESSEL-FRAME metres
-- (right, forward) and converted by geo(), and the night jump is computed from
-- the load-time geometry. What the park DOES have to provide is clear, flat
-- ground: the rig's footprint is a 42 m radius ring plus two lamps out to ~72 m
-- ahead, and the cameras orbit the DG at about 50-80 m.
-- CURRENT PARK (2026-09-13, his): -80.6485750 / +28.5830320, heading 36, which
-- puts the VAB 331 m off the PORT beam (bearing 296.5 true, 55 m aft of abeam).
-- That is outside every lamp's reach - the spots are 250 m and aimed DOWN at the
-- DG, the posts are 120 m - so the VAB is a silhouette in the background here,
-- not a caster or a receiver in any case.
--
-- KEYS (Orbiter's own, no key hooks exist for a scenario script):
--     T       next case        (the "faster" key; the warp is put back to 1x at once)
--     R       previous case    (the "slower" key; same)
--     Ctrl+P  pause - the sequence freezes with the sim
--
-- SETTINGS for a full pass (Launchpad > Video > Advanced setup): Local lights 16x
-- Full, Spot light shadows 6 spot maps, Point light shadows Cube, Terrain and
-- world shadows Cascaded (ORO). Set ShadowDebug = 1 in D3D9Client.cfg when a run
-- is meant for a report: the client then logs "ORO lcl dbg:" once a second and
-- every case names the shape that line should have.
--
-- The lamp classes (Config\Vessels\ORO_LampSpot.cfg / ORO_LampPost.cfg and their
-- meshes) are generated by tools/lampgen.py in the ORO repo. Each lamp is its own
-- vessel with ONE emitter added here, so every other lamp is a caster in its map
-- (the client excludes only the emitter's own vessel).
-- ---------------------------------------------------------------------------

