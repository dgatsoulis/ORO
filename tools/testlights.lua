-- the sun's elevation at the DG, from the three global positions (no oapi horizon call needed)
local hSun = oapi.get_objhandle('Sun')
local function sunElev()
  local up = vec.unit(vec.sub(dg:get_globalpos(), oapi.get_globalpos(hEarth)))
  local toSun = vec.unit(vec.sub(oapi.get_globalpos(hSun), dg:get_globalpos()))
  return math.asin(vec.dotp(up, toSun))
end

-- the rig is a NIGHT test: if the scenario was loaded (or saved) in daylight, the clock
-- is advanced to two hours after the sun passes 8 deg below the horizon. The advance is
-- COMPUTED ONCE from the load-time geometry (latitude, the sun's declination and hour
-- angle, the planet's rotation period) and applied as ONE jump: the first flight's
-- per-frame search stepped the clock 25 h and never saw night, because the positions it
-- sampled did not follow the clock inside that first second. The day case jumps twelve
-- hours from whatever mjd0 ends up being.
local nightForced = false
local function forceNight()
  local e0 = sunElev()
  if e0 < -8 * RAD then return end
  local pE, pD = oapi.get_globalpos(hEarth), dg:get_globalpos()
  local up = vec.unit(vec.sub(pD, pE))
  local s = vec.unit(vec.sub(oapi.get_globalpos(hSun), pD))
  local R = oapi.get_rotationmatrix(hEarth)              -- planet-local -> global; column y = the spin axis
  local axis = vec.unit({ x = R.m12, y = R.m22, z = R.m32 })
  local phi = math.asin(vec.dotp(up, axis))              -- latitude
  local dec = math.asin(vec.dotp(axis, s))               -- the sun's declination
  local east = vec.unit(vec.crossp(up, axis))            -- longitude runs +x -> +z in Orbiter's frame
  local cc = math.cos(phi) * math.cos(dec)
  local kt = (math.sin(-8 * RAD) - math.sin(phi) * math.sin(dec)) / cc
  if kt < -1 or kt > 1 then
    log(string.format('daylight at load (sun %.1f deg) and no night reaches -8 deg at this latitude - left as is', e0 / RAD))
    return
  end
  local k0 = (math.sin(e0) - math.sin(phi) * math.sin(dec)) / cc
  local H0 = math.acos(math.max(-1, math.min(1, k0)))   -- hour angle now, unsigned
  if vec.dotp(east, s) > 0 then H0 = -H0 end            -- sun in the east: morning
  local dH = math.acos(kt) - H0                          -- rotation until the sun sets through -8 deg
  while dH <= 0 do dH = dH + 2 * math.pi end
  local dt = dH / (2 * math.pi) * oapi.get_planetperiod(hEarth) + 2 * 3600
  mjd0 = mjd0 + dt / 86400
  oapi.set_simmjd(mjd0)
  proc.skip()
  nightForced = true
  log(string.format('daylight at load (sun %.1f deg, lat %.1f, dec %.1f) - clock advanced %.2f h to MJD %.4f; sun reads %.1f deg after one frame',
                    e0 / RAD, phi / RAD, dec / RAD, dt / 3600, mjd0, sunElev() / RAD))
end

-- vessel-frame metres (right, forward) -> geographic offset -> lng/lat
local function geo(right, fwd)
  local e = right * math.cos(hdg0) + fwd * math.sin(hdg0)
  local n = fwd * math.cos(hdg0) - right * math.sin(hdg0)
  return dgLng + e / (R0 * math.cos(dgLat)), dgLat + n / R0
end

-- compass heading (rad) from point a to point b, both in vessel-frame metres
local function headingTo(ar, af, br, bf)
  local dr, df = br - ar, bf - af
  local e = dr * math.cos(hdg0) + df * math.sin(hdg0)
  local n = df * math.cos(hdg0) - dr * math.sin(hdg0)
  return math.atan2(e, n)
end

-- ---------------------------------------------------------------------------
-- vessels spawned by the rig
