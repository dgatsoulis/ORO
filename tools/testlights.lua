-- TINTED WHITES OF EQUAL BRIGHTNESS. In a multi-lamp case a shadow is what its lamp
-- contributed, taken away; the eye weighs red and green as brightness and blue hardly at
-- all, and grass reflects little blue to begin with. Saturated primaries (the two-spot
-- flight) made the red lamp's shadow a dark shape and the blue lamp's invisible. With
-- these every shadow is a luminance drop the eye sees, and the tint says which lamp.
local COL = {
  white  = { r = 1.00, g = 0.96, b = 0.88 },
  warm   = { r = 1.00, g = 0.80, b = 0.50 },
  cool   = { r = 0.50, g = 0.75, b = 1.00 },
  pink   = { r = 1.00, g = 0.62, b = 0.72 },
  mint   = { r = 0.55, g = 1.00, b = 0.65 },
  gold   = { r = 1.00, g = 0.92, b = 0.35 },
  lav    = { r = 0.78, g = 0.66, b = 1.00 },
  peach  = { r = 1.00, g = 0.70, b = 0.55 },
  ice    = { r = 0.70, g = 0.90, b = 1.00 },
}
local BLACK = { r = 0, g = 0, b = 0 }
local SPOT_POS = { x = 0, y = 11.89, z = 0.45 }  -- the floodlight head: lampgen.py's 12 m post
local POST_POS = { x = 0, y = 9.85, z = 0 }      -- the globe

-- a spot lamp at (right, fwd) aimed at the point (tr, tf) at height th; the lamp vessel
-- turns to face it, the emitter tilts down to hit it
local function spotLamp(idx, right, fwd, col, tr, tf, th, prm)
  tr, tf, th = tr or 0, tf or 0, th or 1.5
  local hdg = headingTo(right, fwd, tr, tf)
  local v = spawn(string.format('ORO_LAMP_%02d', idx), 'ORO_LampSpot', right, fwd, hdg)
  if v == nil then return nil end
  local dist = math.sqrt((tr - right) ^ 2 + (tf - fwd) ^ 2)
  local tilt = math.atan2(SPOT_POS.y - th, dist)
  prm = prm or {}
  -- FLAT POOLS: 1/(0.25 + 2e-4 d^2) is 3.7x at 10 m, 1.85x at 38 m, 1.0x at 60 m, 0.66x at
  -- 80 m. With the stock-style 1e-3 constant the ground beside each post ran at 10x in one
  -- saturated colour and drowned the other lamp's 1x there - and its shadow with it (the
  -- two-spot flight). A shadow is legible only where the lamps are comparable, so the
  -- whole field is kept between one and two times full intensity.
  local le = v:add_spotlight(SPOT_POS, { x = 0, y = -math.sin(tilt), z = math.cos(tilt) },
    { range = prm.range or 250, att0 = prm.att0 or 0.25, att1 = 0, att2 = prm.att2 or 2e-4,
      umbra = (prm.umbra or 40) * RAD, penumbra = (prm.penumbra or 60) * RAD },
    col or COL.white, col or COL.white, BLACK)
  le:set_visibility(VIS.ALWAYS)
  le:activate(true)
  return v, le
end

-- the mast: a POINT light at the globe, or (aimed) a spot from the globe
local function postLamp(idx, right, fwd, col, prm, aimAt)
  prm = prm or {}
  local hdg = hdg0
  if aimAt then hdg = headingTo(right, fwd, aimAt.r, aimAt.f) end
  local v = spawn(string.format('ORO_POST_%02d', idx), 'ORO_LampPost', right, fwd, hdg)
  if v == nil then return nil end
  local le
  if aimAt then
    local dist = math.sqrt((aimAt.r - right) ^ 2 + (aimAt.f - fwd) ^ 2)
    local tilt = math.atan2(POST_POS.y - (aimAt.h or 1.5), dist)
    le = v:add_spotlight(POST_POS, { x = 0, y = -math.sin(tilt), z = math.cos(tilt) },
      { range = prm.range or 120, att0 = prm.att0 or 0.25, att1 = 0, att2 = prm.att2 or 3e-4,
        umbra = (prm.umbra or 45) * RAD, penumbra = (prm.penumbra or 180) * RAD },
      col or COL.white, col or COL.white, BLACK)
  else
    le = v:add_pointlight(POST_POS,
      { range = prm.range or 120, att0 = prm.att0 or 0.25, att1 = 0, att2 = prm.att2 or 3e-4 },
      col or COL.white, col or COL.white, BLACK)
  end
  le:set_visibility(VIS.ALWAYS)
  le:activate(true)
  return v, le
end

-- a ring of spot lamps round the DG, all aimed at it: n lamps, radius r, start angle a0.
-- A ring's shadows fall INTO the opposite lamps' pools and read as colour shifts; the cones
-- are opened to 90 deg so no dark gap between pools can pass for a shadow.
local RING = { umbra = 70, penumbra = 90, att2 = 3e-4 }
local function spotRing(n, r, a0, cols, prm)
  prm = prm or RING
  for i = 0, n - 1 do
    local a = (a0 + 360 * i / n) * RAD
    spotLamp(i + 1, r * math.sin(a), r * math.cos(a), cols[(i % #cols) + 1], 0, 0, 1.5, prm)
  end
end

-- a FAN of spot lamps on one side of the DG, all aimed at it: n lamps at radius r spread
-- over `span` degrees centred on bearing `centre` (0 = ahead, -90 = port). Every shadow
-- lands on the far side, on ground every lamp lights, as N crisp rays radiating from the
-- hull, each the colour its own lamp is not - the floodlit-pitch look, and the one that
-- shows N maps as N shadows at a glance.
local FAN = { umbra = 45, penumbra = 65, att2 = 3e-4 }
local function spotFan(n, r, centre, span, cols, prm)
  prm = prm or FAN
  for i = 0, n - 1 do
    local a = (centre - span / 2 + span * i / (n - 1)) * RAD
    spotLamp(i + 1, r * math.sin(a), r * math.cos(a), cols[(i % #cols) + 1], 0, 0, 1.5, prm)
  end
end

-- the DG's own beam: a script-owned copy of its landing light (LightSubsys.cpp values),
-- so the case does not depend on the cockpit switch
local dgBeam = nil
local function dgBeamOn(on)
  if on and dgBeam == nil then
    local tilt = 4 * RAD
    dgBeam = dg:add_spotlight({ x = 0.1, y = -0.3, z = 7.5 }, { x = 0, y = -math.sin(tilt), z = math.cos(tilt) },
      { range = 400, att0 = 1e-3, att1 = 0, att2 = 1.5e-4, umbra = 25 * RAD, penumbra = 40 * RAD },
      COL.white, COL.white, BLACK)
    dgBeam:set_visibility(VIS.ALWAYS)
  end
  if dgBeam ~= nil then dgBeam:activate(on) end
end

