local function titleCard()
  local w = {}
  if not cfgFound then w[#w + 1] = 'D3D9Client.cfg not found in the Orbiter root - settings unknown' end
  if S.shadows == 0 then w[#w + 1] = 'Spot light shadows are OFF - every shadow case will show none' end
  if S.maps < 6 and S.shadows ~= 0 then w[#w + 1] = 'cases 5, 7, 8, 10, 11 want 6 spot maps (have ' .. S.maps .. ')' end
  if S.point == 0 then w[#w + 1] = 'Point light shadows OFF - case 9 will show none' end
  if S.point ~= 2 and S.shadows ~= 0 then w[#w + 1] = 'Point light shadows not Cube - case 8\'s flood stays one coarse 166 deg map' end
  if maxLights < 12 then w[#w + 1] = 'case 11 wants 12x or 16x local lights (have ' .. (LIGHTCFG[S.lights] or S.lights) .. ')' end
  if S.terrain ~= 3 then w[#w + 1] = 'Terrain shadows not Cascaded - spot maps use the local atlas (the terrain reads it day and night since 2026-09-19)' end
  if S.debug == 0 then w[#w + 1] = 'ShadowDebug = 0 - set 1 in D3D9Client.cfg for the ORO lcl dbg log line' end
  if nightForced then w[#w + 1] = 'the scenario was in daylight - the clock was advanced to two hours after sunset' end
  local s = 'ORO LIGHTS TEST RIG\n' ..
    string.format('Local lights: %s / Spot light shadows: %s\n', LIGHTCFG[S.lights] or tostring(S.lights),
                  (S.shadows == 0) and 'Off' or (S.maps .. ' spot maps')) ..
    string.format('Point light shadows: %s / Terrain shadows: %s\n', PTMODE[S.point] or tostring(S.point),
                  TERRSHD[S.terrain] or tostring(S.terrain)) ..
    string.format('Vessel self-shadows: %s / ShadowDebug: %d\n', SELFSHD[S.selfshd] or tostring(S.selfshd), S.debug)
  for _, line in ipairs(w) do s = s .. 'WARN: ' .. line .. '\n' end
  s = s .. string.format('%d cases, about %d s each, the camera orbits each one. %s', #cases, 31, KEYS)
  log('settings: lights ' .. tostring(S.lights) .. ' shadows ' .. tostring(S.shadows) .. ' maps ' .. tostring(S.maps) ..
      ' point ' .. tostring(S.point) .. ' terrain ' .. tostring(S.terrain) .. ' selfshd ' .. tostring(S.selfshd) .. ' debug ' .. tostring(S.debug))
  for _, line in ipairs(w) do log('WARN ' .. line) end
  return s
end

local function main()
  oapi.set_tacc(1)
  camTarget(hDG, 7, 0.30, 0.9, 0.05)
  clearRig()
  forceNight()
  local first = titleCard()
  cam.rate = 0.35 * 2 * math.pi / 12
  local key = hold(12, function(left) return first .. string.format(' / %d s', math.ceil(left)) end)
  local i = 1
  while i >= 1 and i <= #cases do
    local c = cases[i]
    log(string.format('case %d/%d - %s', c.n, c.total, c.title))
    c.setup()
    cam.rate = CAM_TURNS * 2 * math.pi / c.dur
    resetDbg()
    proc.skip()
    local r = hold(c.dur, function(left) return caption(c, left) end)
    if c.teardown then c.teardown() end
    clearRig()
    if r == 'back' then i = i - 1 else i = i + 1 end
    if i < 1 then i = 1 end
  end
  oapi.set_simmjd(mjd0)
  dgBeamOn(false)
  camTarget(hDG, 7, 0.30, cam.phi, 0.0)
  hold(8, function(left) return 'LIGHTS TEST - done. Everything the rig spawned is deleted; the DG is yours.\n' ..
                                 'Report: your settings from the title card, the video or unpaused screenshots,\n' ..
                                 'and Orbiter.log (ORO lcl dbg lines if ShadowDebug was 1).' end)
end

local ok, err = pcall(main)
if not ok then
  if err == nil then
    -- the interpreter unwinds a running script with a nil error when the session closes
    log('interrupted - session closing')
  else
    log('ERROR ' .. tostring(err))
    say('LIGHTS TEST - error: ' .. tostring(err))
    pcall(clearRig)
    pcall(function() oapi.set_simmjd(mjd0) end)
    pcall(proc.wait_simdt, 10)
  end
end
pcall(function() oapi.del_annotation(note) end)
log('finished')
