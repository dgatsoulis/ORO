-- ---------------------------------------------------------------------------
-- the camera: track mode round the target; phi is the polar angle from the
-- target's +z (0 = behind it), tht the elevation
-- ---------------------------------------------------------------------------
local CAM_TURNS = 1.15      -- orbits per case: a full turn and a bit, whatever the case length
local cam = { h = hDG, dist = 7.0, tht = 0.30, phi = 1.0, rate = 0.075 }
local function camTarget(h, dist, tht, phi0, rate)
  cam.h = h or hDG; cam.dist = dist or 7.0; cam.tht = tht or 0.30
  cam.phi = phi0 or 1.0; cam.rate = rate or cam.rate      -- the case runner sets the rate from CAM_TURNS
  oapi.set_cameratarget(cam.h, 1)
end
local function camStep(dt)
  cam.phi = cam.phi + cam.rate * dt
  -- Camera::SetRelPos puts the camera at y = sin(tht) * (-distance), so a POSITIVE tht is
  -- below the target (the first flight started under the runway); the cases give the
  -- elevation ABOVE the target and the sign is flipped here, once.
  oapi.set_cameramode({ mode = 'track', trackmode = 'relative', reldist = cam.dist, phi = cam.phi, tht = -cam.tht })
end

-- ---------------------------------------------------------------------------
-- the case runner: sim time paces the case (pause freezes it); T / R are read
-- back as the warp they set and cancelled the same frame
-- ---------------------------------------------------------------------------
local fps = 0
local function hold(dur, textfn)
  local t0 = oapi.get_simtime()
  local tp = oapi.get_simtime()
  local sp = oapi.get_systime()
  while true do
    local t = oapi.get_simtime()
    local left = dur - (t - t0)
    if left <= 0 then return 'next' end
    local ta = oapi.get_tacc()
    if ta > 1.5 then oapi.set_tacc(1); return 'next' end
    if ta < 0.7 then oapi.set_tacc(1); return 'back' end
    local dt = t - tp; tp = t
    local s = oapi.get_systime()
    if s > sp then fps = 0.9 * fps + 0.1 / (s - sp) end
    sp = s
    camStep(dt)
    if textfn then say(textfn(left)) end
    proc.skip()
  end
end

-- single spaces only: the annotation renderer breaks a line at every run of spaces
local KEYS = 'T next / R back / Ctrl+P pause'

-- the client's own instrument, tailed from Orbiter.log: the core opens, appends and closes
-- the file for every line, so the tail is always current. With ShadowDebug at 1 the last
-- "ORO lcl dbg:" line (maps, clusters, fov, range, casters) goes straight into the caption
-- and onto the video; the tester never opens the log. Read once a second.
local dbgLive, dbgNext = nil, 0
local function liveDbg()
  local t = oapi.get_simtime()
  if t < dbgNext then return dbgLive end
  dbgNext = t + 1.0
  local f = io.open('Orbiter.log', 'rb')
  if not f then return dbgLive end
  local size = f:seek('end') or 0
  local back = math.min(size, 16384)
  f:seek('set', size - back)
  local tail = f:read(back) or ''
  f:close()
  local last = nil
  for line in string.gmatch(tail, 'ORO lcl dbg:[^\r\n]*') do last = line end
  if last then dbgLive = last end
  return dbgLive
end
local function resetDbg() dbgLive = nil; dbgNext = 0 end

local function caption(c, left)
  local s = string.format('LIGHTS TEST %d/%d - %s\n', c.n, c.total, c.title)
  s = s .. c.text .. '\n'
  if c.needs then s = s .. 'Needs: ' .. c.needs .. '\n' end
  if c.dbg then
    local live = (S.debug > 0) and liveDbg() or nil
    if live then s = s .. 'Log: ' .. live .. '\n'
    else s = s .. 'Log (ShadowDebug 1): ORO lcl dbg: ' .. c.dbg .. '\n' end
  end
  if c.fps then s = s .. string.format('Frame rate: %.0f fps\n', fps) end
  s = s .. string.format('%s / %d s', KEYS, math.ceil(left))
  return s
end

