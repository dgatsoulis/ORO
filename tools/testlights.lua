local rig = {}      -- name -> { v = interface, h = handle }

-- THE STALE-OBJECT PURGE (a stock Lua interpreter bug, found by the T-key flight of
-- 2026-09-10). Interpreter::lua_pushvessel caches a vessel's Lua object in the registry
-- keyed by its C++ pointer, and the delete hook only strikes the pointer from the validity
-- set (knownVessels) - the registry entry survives. A vessel created after another died is
-- routinely allocated at the freed address, so get_interface hands back the DEAD object and
-- every method on it fails with "Invalid vessel object for self". Detect it, drop the dead
-- registry entry, and fetch again: the interpreter then builds a fresh object.
local function liveVessel(h)
  if h == nil then return nil end
  local v = vessel.get_interface(h)
  if v == nil then return nil end
  if pcall(v.get_name, v) then return v end
  local reg = debug.getregistry()
  for k, val in pairs(reg) do
    if val == v then reg[k] = nil end
  end
  v = vessel.get_interface(h)
  if v ~= nil and pcall(v.get_name, v) then
    log('purged a stale vessel object (interpreter registry) for ' .. v:get_name())
    return v
  end
  return nil
end

local function findVessel(name)
  for i = 0, vessel.get_count() - 1 do
    local v = liveVessel(vessel.get_handle(i))
    if v ~= nil and v:get_name() == name then return v end
  end
  return nil
end

-- create (or re-use a leftover of the same name) and land it at (right, fwd) m from
-- the DG with the given compass heading. arot.x = 10 asks Orbiter to derive the
-- orientation from the heading and the base height from the touchdown points.
local function spawn(name, class, right, fwd, hdg)
  local v = findVessel(name)
  if v == nil or v:get_classname() ~= class then
    if v ~= nil then oapi.del_vessel(name); proc.skip() end
    local h = oapi.create_vessel(name, class, dg:get_rawstatus(1))
    if h == nil then log('could not create ' .. name .. ' (' .. class .. ')'); return nil end
    v = liveVessel(h)
    if v == nil then log('no live interface for ' .. name .. ' (' .. class .. ')'); return nil end
  end
  local lng, lat = geo(right, fwd)
  v:defset_status({ version = 2, status = 1, rbody = hEarth,
                    surf_lng = lng, surf_lat = lat, surf_hdg = hdg,
                    arot = { x = 10, y = 0, z = 0 }, vrot = { x = 0, y = 0, z = 0 } })
  rig[name] = { v = v, h = v:get_handle(), r = right, f = fwd }
  return v
end

local function clearRig()
  for name, _ in pairs(rig) do oapi.del_vessel(name) end
  rig = {}
  proc.skip()
end

